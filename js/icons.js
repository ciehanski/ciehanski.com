// GitHub's octocat mark, redrawn on a 13px grid (the cat is the cut-out).
const GITHUB = [
  '....#####....',
  '..#########..',
  '.##.#####.##.',
  '.#...###...#.',
  '##.........##',
  '##.........##',
  '##.........##',
  '##.........##',
  '###.......###',
  '#.###...#####',
  '.#..#...####.',
  '..###...###..',
  '....#...#....',
];

export function icon(name) {
  const rows = name === 'github' ? GITHUB : ICONS[name] || ICONS.help;
  let rects = '';
  rows.forEach((row, y) => [...row].forEach((c, x) => { if (c === '#') rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`; }));
  return `<svg viewBox="0 0 ${rows[0].length} ${rows.length}" width="18" height="18" shape-rendering="crispEdges" fill="currentColor" aria-hidden="true">${rects}</svg>`;
}

export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((el) => { el.innerHTML = icon(el.dataset.icon); });
}

export function setIcon(el, name) {
  el.dataset.icon = name;
  el.innerHTML = icon(name);
}
